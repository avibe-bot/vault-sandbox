import { afterEach, describe, expect, it, vi } from "vitest"
import * as vaultCrypto from "./vaultCrypto"
import { sealGeneratedStatic } from "./sealOperations"

const envelope: vaultCrypto.ProtectedRecordEnvelope = {
  ciphertext: "sealed-ciphertext",
  nonce: "sealed-nonce",
  wrap_meta: "{}",
}

afterEach(() => vi.restoreAllMocks())

describe("sandbox-generated static sealing", () => {
  it("returns only the envelope and clears generated bytes after sealing", async () => {
    let generatedBytes: Uint8Array | undefined
    vi.spyOn(vaultCrypto, "sealProtected").mockImplementation(async (value) => {
      generatedBytes = value as Uint8Array
      expect(generatedBytes.some((byte) => byte !== 0)).toBe(true)
      return {} as Awaited<ReturnType<typeof vaultCrypto.sealProtected>>
    })
    vi.spyOn(vaultCrypto, "packProtectedRecord").mockReturnValue(envelope)

    const result = await sealGeneratedStatic({
      name: "API_TOKEN",
      generate: { length: 32, charset: "hex" },
      vmk: new Uint8Array(32),
      wrapMeta: "{}",
    })

    expect(result).toEqual({ envelope })
    expect(generatedBytes).toBeDefined()
    expect([...generatedBytes!]).toEqual(new Array(32).fill(0))
  })

  it("clears generated bytes when sealing fails", async () => {
    let generatedBytes: Uint8Array | undefined
    vi.spyOn(vaultCrypto, "sealProtected").mockImplementation(async (value) => {
      generatedBytes = value as Uint8Array
      throw new Error("seal failed")
    })

    await expect(sealGeneratedStatic({
      name: "API_TOKEN",
      generate: { length: 32, charset: "hex" },
      vmk: new Uint8Array(32),
      wrapMeta: "{}",
    })).rejects.toThrow("seal failed")

    expect(generatedBytes).toBeDefined()
    expect([...generatedBytes!]).toEqual(new Array(32).fill(0))
  })
})
